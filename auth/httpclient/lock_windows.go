//go:build windows

package httpclient

import (
	"os"

	// Packages
	windows "golang.org/x/sys/windows"
)

// lockFile locks the file, for this process, until it's unlocked or
// closed, waiting while another process has it
func lockFile(f *os.File) error {
	return windows.LockFileEx(windows.Handle(f.Fd()), windows.LOCKFILE_EXCLUSIVE_LOCK, 0, 1, 0, new(windows.Overlapped))
}

// unlockFile unlocks the file
func unlockFile(f *os.File) error {
	return windows.UnlockFileEx(windows.Handle(f.Fd()), 0, 1, 0, new(windows.Overlapped))
}

// privateMode returns whether files' modes say who can read them, which,
// on Windows, they don't
const privateMode = false
